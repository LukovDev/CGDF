//
// jobsystem.h - Система задач (пул потоков).
//
// При инициализации создаётся по одному рабочему потоку (воркеру) на каждое логическое ядро процессора.
// Воркеры спят и не нагружают процессор, пока нет задач.
// Задача кладётся в очередь (первой пришла - первой выполнится), и система будит один спящий воркер.
// Воркер забирает самую старую задачу, выполняет её и снова засыпает. Если все воркеры заняты,
// задача ждёт в очереди. Если каких-то воркеров не хватает, они досоздаются при следующей задаче.
//
// Не подходит под мелкие задачи.
// Задача не должна вызывать thrd_exit(), а долгие циклы лучше запускать отдельным потоком:
// такая задача навсегда занимает один воркер.
//

#pragma once


// Подключаем:
#include "std.h"
#include "array.h"
#include "libs.h"


// Определения:
typedef int (*JobFunction)(void *args);  // Указатель на функцию, которую мы будем выполнять.


// Объявление структур:
typedef struct JobSystem JobSystem;  // Структура системы задач.
typedef struct JobTask JobTask;      // Задача которую мы будем выполнять.


// Структура системы задач:
struct JobSystem {
    bool initialized;           // Инициализирована ли система задач.
    size_t workers_count;       // Сколько воркеров сейчас выполняют задачу.
    size_t max_workers_count;   // Сколько воркеров должно быть (по числу логических потоков процессора).
    size_t real_workers_count;  // Сколько воркеров сейчас живо.
    Array *queue;               // Очередь задач (в конец кладём, из начала забираем).
    mtx_t mutex;                // Мьютекс для защиты очереди и счётчиков.
    cnd_t cond_var;             // Условная переменная: на ней спят воркеры, пока нет задач.
};


// Структура задачи:
struct JobTask {
    JobFunction function;  // Функция, которую мы будем выполнять.
    void *args;            // Аргумент задачи.
};


// Глобальный объект системы задач (пул потоков):
extern JobSystem g_JobSystem;


// Инициализация системы задач:
void JobSystem_init(void);

// Уничтожение системы задач (ждёт, пока доработают выполняющиеся задачи, а задачи из очереди выкидывает):
void JobSystem_destroy(void);

// Поставить задачу в очередь:
void JobSystem_create_job(JobFunction func, void *args);

// Есть ли задачи в работе или в очереди:
bool JobSystem_has_active_jobs(void);

// Получить количество задач в очереди:
size_t JobSystem_get_jobs_count(void);

// Получить количество воркеров, занятых задачей:
size_t JobSystem_get_active_workers_count(void);

// Получить количество живых воркеров:
size_t JobSystem_get_real_workers_count(void);

// Получить сколько воркеров должно быть:
size_t JobSystem_get_max_workers_count(void);
